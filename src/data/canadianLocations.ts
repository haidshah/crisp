export function getProvinceTaxRate(provinceCode?: string): number {
  if (!provinceCode) return 0.13; // default Ontario
  const upper = provinceCode.toUpperCase() as ProvinceCode;
  return PROVINCE_TAX_MAP[upper] ?? 0.13;
}

export function getProvinceTaxLabel(provinceCode?: string): string {
  const prov = getProvinceByCode(provinceCode);
  return prov ? prov.taxLabel : '13% HST';
}

export function getProvinceByCode(provinceCode?: string): CanadianProvince | undefined {
  return CANADIAN_PROVINCES.find(p => p.code === provinceCode?.toUpperCase());
}

export function isPrimaryServiceArea(city?: string, province?: string): boolean {
  if (!city && !province) return true; // Default Cambridge is primary
  const c = (city || '').toLowerCase();
  const p = (province || 'ON').toUpperCase();
  
  if (p === 'ON') {
    const primaryCities = [
      'cambridge', 'kitchener', 'waterloo', 'guelph', 'brantford', 
      'paris', 'ayr', 'north dumfries', 'milton', 'hamilton', 
      'burlington', 'oakville', 'mississauga', 'brampton', 'toronto',
      'hespeler', 'galt', 'preston', 'elmira', 'st. jacobs', 'badgers'
    ];
    return primaryCities.some(pc => c.includes(pc) || pc.includes(c));
  }
  return false;
}

export function findProvinceByCity(cityName: string): CanadianProvince | undefined {
  const clean = cityName.trim().toLowerCase();
  for (const prov of CANADIAN_PROVINCES) {
    if (prov.majorCities.some(mc => mc.toLowerCase().includes(clean) || clean.includes(mc.toLowerCase()))) {
      return prov;
    }
  }
  // Check regions
  for (const reg of ALL_CANADIAN_REGIONS) {
    if (reg.city && (reg.city.toLowerCase().includes(clean) || clean.includes(reg.city.toLowerCase()))) {
      return CANADIAN_PROVINCES.find(p => p.code === reg.province);
    }
  }
  return undefined;
}

